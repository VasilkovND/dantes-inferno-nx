#!/usr/bin/env python3
"""Calls the compiler may inline (make_nx_pch.py's DEFINE_REX_FUNC).

Every recompiled function is a weak, noinline alias (name) of its body (__imp__name), so that a hook can replace it:
each call, even to a three-instruction getter, is a real call with the guest registers going through memory. A call to
a function defined in the same file that no hook replaces is rewritten to call the body directly, which GCC may inline
(it decides by size; the big ones stay calls). The game's Presentation thread is the busy one and its profile is flat
(hundreds of small functions), so this is where the call overhead adds up. (From gears2-nx, Gears of War 2's port.)

The hooked functions: this game's hooks replace a named guest function by defining a strong symbol of that name
(REX_EXTERN(VP6_DecodeFrameMbs) { ... }, DANTE_SKIN(SkinVerts4, 4) ...), and call the original as __imp__<name>. So any
generated function whose name appears in the sources the build compiles (dante/src, the SDK) counts as hooked: its
calls keep going through the alias.

The register save/restore helpers (__savegprlr_N, __restgprlr_N, __savefpr_N, __restfpr_N, __savevmx_N, __restvmx_N)
are a fifth of all calls and each is defined in one file only: their bodies are copied into
dantes_inferno_inline_helpers.h as always-inline functions (rex_inl___savegprlr_26 ...), every file includes it, and
every call to a helper becomes a call to its copy, so the stores and loads land in the caller.

Usage: patch_inline_calls.py <source dir>... -- generated/default/dantes_inferno_recomp.*.cpp   (idempotent)
"""

import re
import sys
from pathlib import Path

HELPER = r"__(?:save|rest)(?:gpr|gprlr|fpr|vmx)_\d+"
DEFINE = re.compile(r"^DEFINE_REX_FUNC\(([A-Za-z_]\w*)\)", re.M)
CALL = re.compile(r"(?<![\w])([A-Za-z_]\w*)\(ctx, base\);")
IDENT = re.compile(r"\b[A-Za-z_]\w*\b")
COMMENT = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)


def hooked_names(dirs, defined):
    """The generated functions (of `defined`) the sources name outside comments: hooked, or called from native code.
    The SDK's code generator (codegen/ folders, not in the NRO) names the helpers it looks for: skipped."""
    names = set()
    for d in dirs:
        for p in Path(d).rglob("*"):
            if p.suffix in (".cpp", ".h", ".hpp", ".cc", ".inc") and p.is_file() and "codegen" not in p.parts:
                text = COMMENT.sub(" ", p.read_text(encoding="utf-8", errors="replace"))
                for w in IDENT.findall(text):
                    if w.startswith("__imp__"):
                        w = w[len("__imp__"):]
                    if w in defined:
                        names.add(w)
    return names


def defined_names(paths):
    names = set()
    for p in paths:
        names.update(DEFINE.findall(Path(p).read_text(encoding="utf-8", errors="surrogateescape")))
    return names


def patch(path, hooked):
    text = Path(path).read_text(encoding="utf-8", errors="surrogateescape")
    local = {n for n in DEFINE.findall(text) if not re.fullmatch(HELPER, n)} - hooked
    count = 0

    def repl(m):
        nonlocal count
        if m.group(1) in local:
            count += 1
            return "__imp__" + m.group(0)
        return m.group(0)

    new = CALL.sub(repl, text)
    if count:
        Path(path).write_text(new, encoding="utf-8", errors="surrogateescape")
    return count


HELPER_DEF = re.compile(r"^DEFINE_REX_FUNC\((" + HELPER + r")\) \{\n(.*?)^\}\n", re.M | re.S)
HELPER_CALL = re.compile(r"(?<![\w])(" + HELPER + r")\(ctx, base\);")
HEADER = "dantes_inferno_inline_helpers.h"
INCLUDE = '#include "' + HEADER + '"\n'


def write_helpers(paths, hooked):
    bodies = {}
    for p in paths:
        text = Path(p).read_text(encoding="utf-8", errors="surrogateescape")
        for name, body in HELPER_DEF.findall(text):
            if name not in hooked and "goto " not in body and "loc_" not in body:
                bodies[name] = body
    out = ["// Generated by tools/patch_inline_calls.py: the register save/restore helpers, inlined at every call.",
           "#pragma once", ""]
    for name in sorted(bodies):
        out.append(f"static inline __attribute__((always_inline)) void rex_inl_{name}(PPCContext& __restrict ctx, "
                   f"uint8_t* base) {{")
        out.append(bodies[name].rstrip("\n"))
        out.append("}")
        out.append("")
    Path(paths[0]).with_name(HEADER).write_text("\n".join(out), encoding="utf-8")
    return set(bodies)


def inline_helpers(path, helpers):
    text = Path(path).read_text(encoding="utf-8", errors="surrogateescape")
    count = 0

    def repl(m):
        nonlocal count
        if m.group(1) in helpers:
            count += 1
            return "rex_inl_" + m.group(0)
        return m.group(0)

    new = HELPER_CALL.sub(repl, text)
    if INCLUDE not in new:
        first = new.find("\n") + 1  # after #include "dantes_inferno_funcs.N.h"
        new = new[:first] + INCLUDE + new[first:]
    if new != text:
        Path(path).write_text(new, encoding="utf-8", errors="surrogateescape")
    return count


def main(argv):
    if "--" not in argv:
        sys.exit(__doc__)
    i = argv.index("--")
    files = argv[i + 1:]
    hooked = hooked_names(argv[:i], defined_names(files))
    total = sum(patch(p, hooked) for p in files)
    helpers = write_helpers(files, hooked)
    inlined = sum(inline_helpers(p, helpers) for p in files)
    print(f"patch_inline_calls: {total} same-file calls may be inlined, {inlined} helper calls inlined "
          f"({len(helpers)} helpers); {len(hooked)} hooked functions kept as calls: {' '.join(sorted(hooked))}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
