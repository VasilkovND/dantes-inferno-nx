#!/usr/bin/env python3
"""Copies of hot recompiled functions with the guest registers in local variables.

The generated code keeps every PowerPC register in the PPCContext (ctx.r3, ctx.v62, ...), in memory. Guest memory is
written through the `base` pointer, which GCC must assume may point into the context, so every register is reloaded and
stored around every guest load and store: a VMX-heavy function (the VP6 video decoder's block reconstruction, ~3,000
instructions of IDCT and pixel packing) spends most of its time moving registers between the context and NEON.

Here each listed function is copied with the registers it uses (GPRs, FPRs, vector, CR fields, CTR, XER) as locals:
loaded from the context on entry, all stored to it before every call and every return, reloaded after every call. Within
the function they are values GCC can keep in registers. The context is still right wherever anything else can see it,
so the copy behaves as the original. LR, MSR, FPSCR and the reservation stay in the context.

A function is refused (and left alone) if it uses the context in any other way than `ctx.<register>` or a call
`<name>(ctx, base)`.

Usage: localize_regs.py <generated/default> <out.cpp> name[=new_name] ...
The copy of `name` is `<name>_local` unless new_name is given; the caller decides which one runs (dante_video.cpp).
"""
import re
import sys
from pathlib import Path

REG = re.compile(r"\bctx\.(r\d+|f\d+|v\d+|cr[0-7]|ctr|xer)\b")
CALL = re.compile(r"\b([A-Za-z_]\w*)\(ctx, base\);")
FUNC = re.compile(r"^DEFINE_REX_FUNC\((\w+)\) \{\n", re.M)


def find(gen: Path, name: str):
    for f in sorted(gen.glob("*.cpp")):
        t = f.read_text()
        m = re.search(rf"^DEFINE_REX_FUNC\({name}\) \{{\n", t, re.M)
        if not m:
            continue
        nxt = FUNC.search(t, m.end())
        end = nxt.start() if nxt else len(t)
        body = t[m.end():end]
        close = body.rstrip().rfind("}")
        return body[:close]
    sys.exit(f"{name}: not found in {gen}")


def localize(name: str, new: str, body: str) -> str:
    used = sorted(set(REG.findall(body)), key=lambda r: (r.rstrip("0123456789"), int(re.sub(r"\D", "", r) or 0)))
    rest = REG.sub("", body)
    rest = CALL.sub("", rest)
    rest = re.sub(r"\bctx\.(lr|fpscr|msr|reserved\w*|last_indirect_target)\b", "", rest)
    if re.search(r"\bctx\b", rest):
        where = rest[max(0, rest.find("ctx") - 80):rest.find("ctx") + 80]
        raise ValueError(f"{name}: other use of ctx: ...{where}...")
    # Every register it uses is stored back, not only those it seems to write: a missed write would be a wrong value
    # in a caller, and a few dozen stores at a call or return cost little next to the body.
    out_regs = used
    load = " ".join(f"l_{r} = ctx.{r};" for r in used)
    store = " ".join(f"ctx.{r} = l_{r};" for r in out_regs)
    decls = "\n".join(f"\tdecltype(ctx.{r}) l_{r} = ctx.{r};" for r in used)
    b = REG.sub(lambda m: f"l_{m.group(1)}", body)
    b = CALL.sub(lambda m: f"{{ {store} {m.group(1)}(ctx, base); {load} }}", b)
    b = re.sub(r"\breturn;", f"{{ {store} return; }}", b)
    return (f"// {name} with its {len(used)} registers in locals.\n"
            f"REX_FUNC({new}) {{\n{decls}\n{b}\t{{ {store} }}\n}}\n")


def main() -> None:
    gen, out = Path(sys.argv[1]), Path(sys.argv[2])
    parts = ['// Generated by dante/tools/localize_regs.py from the recompiled code: not committed.\n'
             '#include "dantes_inferno_pch.h"\n\n']
    for arg in sys.argv[3:]:
        name, _, new = arg.partition("=")
        parts.append(localize(name, new or f"{name}_local", find(gen, name)))
        parts.append("\n")
    text = "".join(parts)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    print(f"localize_regs: {len(sys.argv) - 3} function(s) -> {out}")


if __name__ == "__main__":
    main()
